# agregação é um tipo de associação onde um objeto
# pode fazer parte de outro objeto, mas ambos têm
# ciclos de vida independentes.
# Ou seja, se o objeto "todo" for destruído,
# o objeto "parte" pode continuar existindo.

# composição é representada por uma relação "tem-um"
# entre os objetos, onde o objeto "todo" contém
# o objeto "parte" como um atributo.
# Na composição, o ciclo de vida do objeto "parte"
# está ligado ao ciclo de vida do objeto "todo".